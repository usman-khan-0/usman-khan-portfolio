// Render blog cards on the homepage
function renderBlogCards() {
    blogGrid.innerHTML = '';
    
    allBlogPosts.forEach(post => {
        const blogCard = document.createElement('article');
        blogCard.className = 'blog-card';
        blogCard.innerHTML = `
            <div class="card-image">
                <img src="${post.image}" alt="${post.title}" loading="lazy">
            </div>
            <div class="card-content">
                <div class="card-meta">
                    <span><i class="far fa-calendar"></i> ${post.date}</span>
                    <span><i class="far fa-clock"></i> ${post.readTime}</span>
                </div>
                <h3>${post.title}</h3>
                <p class="card-excerpt">${post.excerpt}</p>
                <button class="btn btn-secondary read-more" data-id="${post.id}">Read More</button>
            </div>
        `;
        
        blogGrid.appendChild(blogCard);
    });
    
    // Add event listeners to all "Read More" buttons
    document.querySelectorAll('.read-more').forEach(button => {
        button.addEventListener('click', function() {
            const postId = parseInt(this.getAttribute('data-id'));
            openBlogPost(postId);
            
            // Update URL without page reload
            const newUrl = `${window.location.pathname}?post=${postId}`;
            window.history.pushState({ postId }, '', newUrl);
        });
    });
}

// Open a specific blog post
function openBlogPost(postId) {
    const post = allBlogPosts.find(p => p.id === postId) || blogPosts[0];
    
    // Update post content
    postContent.innerHTML = post.content;
    
    // Show the blog post detail section and hide the blog grid
    document.querySelector('.blog-container').style.display = 'none';
    document.querySelector('.about-section').style.display = 'none';
    document.querySelector('.resources-section').style.display = 'none';
    document.querySelector('.hero').style.display = 'none';
    
    blogPostDetail.style.display = 'block';
    
    // Scroll to top of the page
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

// Setup event listeners
function setupEventListeners() {
    // Back to blog button
    backToBlogBtn.addEventListener('click', function() {
        blogPostDetail.style.display = 'none';
        
        // Show all sections again
        document.querySelector('.blog-container').style.display = 'block';
        document.querySelector('.about-section').style.display = 'block';
        document.querySelector('.resources-section').style.display = 'block';
        document.querySelector('.hero').style.display = 'block';
        
        // Update URL
        window.history.pushState({}, '', window.location.pathname);
        
        // Scroll to blog section
        document.querySelector('#blog').scrollIntoView({ behavior: 'smooth' });
    });
    
    // Mobile menu toggle
    menuToggle.addEventListener('click', function() {
        navMenu.classList.toggle('active');
        menuToggle.innerHTML = navMenu.classList.contains('active') 
            ? '<i class="fas fa-times"></i>' 
            : '<i class="fas fa-bars"></i>';
    });
    
    // Close mobile menu when clicking a link
    document.querySelectorAll('.nav-menu a').forEach(link => {
        link.addEventListener('click', function() {
            navMenu.classList.remove('active');
            menuToggle.innerHTML = '<i class="fas fa-bars"></i>';
        });
    });
    
    // Handle browser back/forward buttons
    window.addEventListener('popstate', function(event) {
        if (event.state && event.state.postId) {
            openBlogPost(event.state.postId);
        } else {
            blogPostDetail.style.display = 'none';
            document.querySelector('.blog-container').style.display = 'block';
            document.querySelector('.about-section').style.display = 'block';
            document.querySelector('.resources-section').style.display = 'block';
            document.querySelector('.hero').style.display = 'block';
        }
    });
    
    // Newsletter subscription form
    if (subscribeForm) {
        subscribeForm.addEventListener('submit', function(e) {
            e.preventDefault();
            const emailInput = this.querySelector('input[type="email"]');
            const email = emailInput.value.trim();
            
            if (email) {
                // In a real application, you would send this to a server
                alert(`Thank you for subscribing with email: ${email}. You'll receive updates about the latest AI insights.`);
                emailInput.value = '';
            }
        });
    }
    
    // Smooth scrolling for anchor links
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function(e) {
            const targetId = this.getAttribute('href');
            
            if (targetId === '#') return;
            
            const targetElement = document.querySelector(targetId);
            
            if (targetElement) {
                e.preventDefault();
                
                // Close mobile menu if open
                navMenu.classList.remove('active');
                menuToggle.innerHTML = '<i class="fas fa-bars"></i>';
                
                // Scroll to target
                targetElement.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });
}

